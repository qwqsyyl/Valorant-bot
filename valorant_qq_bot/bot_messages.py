def reminder_added(name, *, enabled=True):
    text = f'已添加皮肤提醒：{name}。\n这款皮肤出现在你的每日商店时，机器人会在本群 @ 你。'
    if not enabled:
        text = f'已保存想要的皮肤：{name}。\n自动提醒暂不可用。'
    return text + '\n请核对完整皮肤名和武器名。发送「愿望单」可查看或管理提醒。'


def wishlist(wishes):
    if not wishes:
        return '你还没有添加皮肤提醒。\n发送「皮肤提醒 皮肤完整名称」添加一款想要的皮肤，出现时会在本群 @ 你。'
    return ('你的愿望单：\n'
            + '\n'.join(f'{i}. {wish.name}' for i, wish in enumerate(wishes, 1))
            + '\n\n想删除某一项，请发送「取消提醒 编号」，例如「取消提醒 1」。')


def reminder_removed(name):
    return f'已取消皮肤提醒：{name}。\n其他皮肤提醒会保留，可发送「愿望单」查看。'


def error_reply(error, *, binding_command=None):
    text = str(error)
    if text in SCAN_ERRORS:
        return SCAN_ERRORS[text]
    if text in ACCOUNT_ERRORS:
        return ACCOUNT_ERRORS[text]
    retry = binding_command or '瓦绑定'
    if '二维码已过期' in text or '扫码超时' in text:
        return f'这张二维码已过期，本次扫码未完成。请发送「{retry}」获取新二维码；已有绑定和皮肤提醒会保留。'
    if text == '微信授权已取消':
        return f'你已取消微信授权，本次绑定未完成。需要再次绑定时，请发送「{retry}」。'
    if binding_command:
        return f'本次授权未完成。请稍后发送「{retry}」重新扫码；若反复失败，请联系群管理员。'
    if isinstance(error, AuthExpiredError):
        return '该账号的掌瓦登录已失效。请账号本人在群里发送「瓦绑定 重新授权」重新扫码，同一账号的绑定和皮肤提醒会保留。'
    if isinstance(error, RenewalError):
        return '暂时无法查看该账号的商店，请稍后再试。若持续失败，请账号本人发送「瓦绑定 重新授权」重新扫码。'
    if '当前商店周期' in text or '周期尚未更新' in text:
        return '今天的商店暂时无法查看，请稍后再试。'
    return '暂时无法查询商店，请稍后再试。若持续失败，请联系群管理员。'
